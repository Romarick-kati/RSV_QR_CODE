const W = 96;
const H = 48;

function buildDots() {
  const dots = [];
  // Thin the longitude step near the poles so dot density stays even.
  for (let r = 0; r < H; r++) {
    const lat = 90 - ((r + 0.5) * 180) / H;
    const step = Math.max(1, Math.round(1 / Math.max(Math.cos((lat * Math.PI) / 180), 0.12)));
    for (let c = 0; c < W; c += step) {
      const lon = -180 + ((c + 0.5) * 360) / W;
      dots.push({ lat: (lat * Math.PI) / 180, lon: (lon * Math.PI) / 180, land: LAND[r][c] === '1' });
    }
  }
  return dots;
}
const DOTS = buildDots();

export default function Globe({ size = 320, speed = 0.0004, tilt = 0.4, className = '', land = '#22D3A6', sea = 'rgba(148,163,184,0.22)', glow = 'rgba(34,211,166,0.35)' }) {
  const ref = useRef(null);

  useEffect(() => {
    const canvas = ref.current;
    if (!canvas) return undefined;
    const ctx = canvas.getContext('2d');
    if (!ctx) return undefined;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = size * dpr;
    canvas.height = size * dpr;
    ctx.scale(dpr, dpr);
    const R = size * 0.42;
    const cx = size / 2;
    const cy = size / 2;
    const reduce = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
    let raf = 0;
    let visible = true;
    let rot = -0.35; // start facing Africa/Europe
    let last = performance.now();

    function draw(now) {
      const dt = Math.min(now - last, 64);
      last = now;
      if (!reduce) rot += dt * speed * 6;
      ctx.clearRect(0, 0, size, size);

      // Glow only outside the sphere's edge (transparent inside, so the
      // dots stay readable), plus a faint disc to give the globe body.
      const halo = ctx.createRadialGradient(cx, cy, R * 0.92, cx, cy, R * 1.3);
      halo.addColorStop(0, 'rgba(0,0,0,0)');
      halo.addColorStop(0.25, glow);
      halo.addColorStop(1, 'rgba(0,0,0,0)');
      ctx.fillStyle = halo;
      ctx.beginPath();
      ctx.arc(cx, cy, R * 1.3, 0, Math.PI * 2);
      ctx.fill();
      ctx.fillStyle = 'rgba(148,163,184,0.07)';
      ctx.beginPath();
      ctx.arc(cx, cy, R, 0, Math.PI * 2);
      ctx.fill();

      const sinT = Math.sin(tilt);
      const cosT = Math.cos(tilt);
      for (let i = 0; i < DOTS.length; i++) {
        const d = DOTS[i];
        const lon = d.lon + rot;
        const x = Math.cos(d.lat) * Math.sin(lon);
        const y0 = Math.sin(d.lat);
        const z0 = Math.cos(d.lat) * Math.cos(lon);
        const y = y0 * cosT - z0 * sinT;
        const z = y0 * sinT + z0 * cosT;
        if (z <= 0) continue; // far side
        ctx.globalAlpha = 0.25 + z * 0.75;
        ctx.fillStyle = d.land ? land : sea;
        ctx.beginPath();
        ctx.arc(cx + x * R, cy - y * R, d.land ? 1.5 + z * 0.9 : 0.9, 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.globalAlpha = 1;
      if (visible && !reduce) raf = requestAnimationFrame(draw);
    }

    raf = requestAnimationFrame(draw);
    const io = new IntersectionObserver(([entry]) => {
      visible = entry.isIntersecting;
      cancelAnimationFrame(raf);
      if (visible) { last = performance.now(); raf = requestAnimationFrame(draw); }
    });
    io.observe(canvas);
    return () => { cancelAnimationFrame(raf); io.disconnect(); };
  }, [size, speed, tilt, land, sea, glow]);

  return <canvas ref={ref} className={className} style={{ width: size, height: size, maxWidth: '100%' }} aria-hidden="true" />;
}
